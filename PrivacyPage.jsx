import { useNavigate } from 'react-router-dom';

const PrivacyPage = () => {
  const navigate = useNavigate();

  const isAccepted = localStorage.getItem('privacyAccepted') === 'true';

  const handleAccept = () => {
    localStorage.setItem('privacyAccepted', 'true');
    navigate('/');
  };

  return (
    <div className="privacy-page">
      <div className="privacy-container">
        <h1>Политика конфиденциальности SkinStar</h1>
        <p className="privacy-intro">
          Маркетплейс SkinStar уважает вашу приватность. Мы обрабатываем персональные данные только для работы сервиса: покупки/продажи скинов, авторизации, поддержки и модерации.
        </p>

        <div className="privacy-text">
          <h3>Какие данные мы собираем</h3>
          <p>Для регистрации и работы на маркетплейсе мы запрашиваем минимально необходимые данные: логин, email, никнейм, аватар. При оформлении сделок дополнительно могут фиксироваться история операций, статусы заказов и сообщения в чате поддержки.</p>

          <h3>Как мы используем данные</h3>
          <p>Данные используются для авторизации, обработки транзакций, показа релевантных предложений, модерации объявлений и защиты от мошенничества. Мы не передаём персональные данные третьим лицам для рекламы или иных целей без вашего согласия.</p>

          <h3>Безопасность и хранение</h3>
          <p>Персональные данные и история сделок хранятся в зашифрованном виде. Срок хранения — пока вы пользуетесь сервисом. Для защиты транзакций применяются стандартные меры безопасности. Любые платёжные данные обрабатываются сторонними платёжными провайдерами и не хранятся на наших серверах.</p>

          <h3>Модерация и контент</h3>
          <p>Мы модерируем объявления и чаты, чтобы исключить мошенничество и запрещённый контент. В случае нарушения правил мы можем временно или навсегда ограничить доступ к функционалу продажи/покупки и заблокировать аккаунт. Сообщения в чате поддержки могут сохраняться для улучшения качества обслуживания.</p>

          <h3>Изменения в политике</h3>
          <p>Мы можем обновлять политику конфиденциальности. При существенных изменениях мы уведомим пользователей. Актуальная версия всегда доступна по ссылке в футере сайта.</p>
        </div>

        <button
          className="btn-accept"
          onClick={handleAccept}
          disabled={isAccepted}
        >
          {isAccepted ? 'Условия приняты' : 'Я принимаю условия'}
        </button>
      </div>
    </div>
  );
};

